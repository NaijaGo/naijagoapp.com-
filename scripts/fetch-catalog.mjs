// Snapshots the public NaijaGo catalogue into src/data/catalog.js for the
// /shop/ category pages. Run `npm run catalog` before `npm run build:root` to
// refresh prices and products; the build itself never calls the API, so a slow
// or sleeping backend can't break a deploy.
//
// Only product name, price, photo and subcategory are kept. Vendor details
// (phone numbers, addresses, locations) are never written to the website.
import fs from "node:fs/promises";
import path from "node:path";
import { shopCategories } from "../src/seo/shopCategories.js";

const API = process.env.API_BASE_URL || "https://naijago-backend.onrender.com";
const PAGE_SIZE = 300;
const SHOWCASE_SIZE = 24;

// Small, compressed images for mobile data: 400px square, auto format/quality.
const thumbnail = (url) =>
  /res\.cloudinary\.com\/[^/]+\/image\/upload\//.test(url)
    ? url.replace("/image/upload/", "/image/upload/w_400,h_400,c_fill,f_auto,q_auto/")
    : url;

const fetchPage = async (page) => {
  const response = await fetch(`${API}/api/products?limit=${PAGE_SIZE}&page=${page}`, {
    signal: AbortSignal.timeout(90_000),
  });
  if (!response.ok) throw new Error(`Products page ${page}: HTTP ${response.status}`);
  const body = await response.json();
  return Array.isArray(body) ? body : body.products || [];
};

const run = async () => {
  const products = [];
  for (let page = 1; page <= 20; page += 1) {
    const batch = await fetchPage(page);
    products.push(...batch);
    if (batch.length < PAGE_SIZE) break;
  }
  if (products.length === 0) throw new Error("The API returned no products; keeping the old snapshot.");

  const catalog = {};
  for (const category of shopCategories) {
    const matches = products.filter((product) => {
      const [top, sub = ""] = String(product.category || "").split(" > ");
      return category.sources.includes(top) && !category.excludeSubcategories?.includes(sub);
    });
    const vendorIds = new Set(matches.map((product) => product.vendor?._id).filter(Boolean));
    // Newest first, one photo per product, skip anything without a photo or price.
    const showcase = matches
      .filter((product) => product.imageUrls?.[0] && Number(product.effectivePrice ?? product.price) > 0)
      .sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt)))
      .slice(0, SHOWCASE_SIZE)
      .map((product) => ({
        id: String(product._id),
        name: String(product.name).trim().slice(0, 90),
        price: Number(product.effectivePrice ?? product.price),
        subcategory: String(product.category).split(" > ")[1] || "",
        image: thumbnail(product.imageUrls[0]),
      }));
    catalog[category.slug] = {
      productCount: matches.length,
      vendorCount: vendorIds.size,
      products: showcase,
    };
    console.log(`${category.slug.padEnd(16)} ${String(matches.length).padStart(4)} products, ${vendorIds.size} vendors`);
  }

  const out = path.join(process.cwd(), "src", "data", "catalog.js");
  await fs.mkdir(path.dirname(out), { recursive: true });
  const updated = new Date().toISOString().slice(0, 10);
  await fs.writeFile(
    out,
    `// Generated by scripts/fetch-catalog.mjs on ${updated}. Do not edit by hand.\n` +
      `export const catalogUpdated = ${JSON.stringify(updated)};\n` +
      `export const catalog = ${JSON.stringify(catalog, null, 2)};\n`,
    "utf8",
  );
  console.log(`Wrote ${out}`);
};

run().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
